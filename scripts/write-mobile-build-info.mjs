/**
 * Embeds commit + build metadata into the mobile bundle (runs before Android build).
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const MOBILE_ROOT = join(ROOT, "apps/mobile");
const APP_JSON_PATH = join(MOBILE_ROOT, "app.json");
const OUT_PATH = join(MOBILE_ROOT, "src/config/build-info.generated.ts");

function shortSha(raw) {
  const value = raw?.trim();
  if (!value) return "unknown";
  return value.slice(0, 7);
}

function resolveGitSha() {
  const fromEnv = (
    process.env.RAILWAY_GIT_COMMIT_SHA ??
    process.env.VERCEL_GIT_COMMIT_SHA ??
    process.env.GIT_COMMIT ??
    ""
  ).trim();
  if (fromEnv) return fromEnv;

  try {
    return execSync("git rev-parse HEAD", { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

function resolveBranch() {
  try {
    return execSync("git rev-parse --abbrev-ref HEAD", { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

const appJson = JSON.parse(readFileSync(APP_JSON_PATH, "utf8"));
const gitSha = resolveGitSha();
const version = String(appJson.expo?.version ?? "0.0.0");
const versionCode = Number(appJson.expo?.android?.versionCode ?? 1);
const releaseChannel = String(appJson.expo?.extra?.releaseChannel ?? "alpha");

const payload = {
  version,
  versionName: `${version}-alpha`,
  versionCode,
  commit: shortSha(gitSha),
  gitSha,
  buildTime: process.env.BUILD_TIME ?? new Date().toISOString(),
  environment: releaseChannel,
  branch: resolveBranch(),
  packageName: String(appJson.expo?.android?.package ?? "ru.lot.marketplace.alpha"),
};

const contents = `/** Auto-generated by scripts/write-mobile-build-info.mjs — do not edit */
export const MOBILE_BUILD_INFO = ${JSON.stringify(payload, null, 2)} as const;
`;

writeFileSync(OUT_PATH, contents);
console.log("mobile-build-info:", payload);
